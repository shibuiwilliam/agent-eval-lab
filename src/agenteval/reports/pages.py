"""結果ページの生成（`docs/results/EX-Y.md` と `EX-Y.en.md`）。

5 項目はレジストリ（= カタログ）から写す。方法・気づきは実験スクリプトが書いた文章を使う。
数値には必ず来歴ラベルを付ける。

英語版は同じ `result` から描き、文章だけを `experiments/registry.en.yaml` から差し替える
（`reports.i18n`）。数値・図・判定は言語に依存しないので、2 言語で食い違うことがない。
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from agenteval.llm.cost import REPO_ROOT
from agenteval.reports import i18n

RESULTS_DIR = REPO_ROOT / "docs" / "results"

TEMPLATE = """# {id} {title}

## 5項目
- 仮説: {hypothesis}
- 植込み条件: {planted}
- 対照: {control}
- 合格基準: {criteria}
- 来歴: {provenance}

## 方法
{method}

## 結果
{table}
{figures}

## 判定
{verdict}

{verdict_reason}

## 気づき・限界
{notes}

---
生成: `uv run agenteval exp {script_id}` / 実行時刻 {ran_at} / コスト {usd} USD
"""

TEMPLATE_EN = """# {id} {title}

*日本語版: [{id}.md]({id}.md)*

## The five items
- Hypothesis: {hypothesis}
- Planted condition: {planted}
- Control: {control}
- Pass criteria: {criteria}
- Provenance: {provenance}

## Method
{method}

## Results
{table}
{figures}

## Verdict
{verdict}

{verdict_reason}

## Findings and limitations
{notes}

---
Generated by `uv run agenteval exp {script_id}` / run at {ran_at} / cost {usd} USD
"""


def format_value(value: Any) -> str:
    """数値と来歴ラベルを 1 セルにする。"""
    if isinstance(value, dict) and "value" in value:
        raw = value["value"]
        text = (
            f"{raw:.4g}"
            if isinstance(raw, (int, float)) and not isinstance(raw, bool)
            else str(raw)
        )
        return f"{text} [{value.get('provenance', '?')}]"
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def provisional_mark(criterion: dict[str, Any], lang: str = "ja") -> str:
    """registry の `provisional: true` の基準に付ける印（パイロットで確定する前の基準。ADR-033）。"""
    if not criterion.get("provisional"):
        return ""
    return " (provisional)" if lang == "en" else "（暫定）"


def metrics_table(metrics: dict[str, Any], criteria: list[dict[str, Any]], lang: str = "ja") -> str:
    """指標の表。合格基準に対応する行には基準と可否を書く。

    `applies_if` を持つ基準は、基準の欄に適用条件を併記し、判定の欄に条件が偽なら N/A（理由つき）、
    条件の指標が無い・来歴ラベルが無ければ ×（理由つき）と書く（ADR-045）。
    """
    by_metric = {c["metric"]: c for c in criteria}
    header = (
        "| Metric | Value (provenance) | Criterion | OK |"
        if lang == "en"
        else "| 指標 | 値（来歴） | 基準 | 判定 |"
    )
    lines = [header, "|---|---|---|---|"]
    for key in sorted(metrics):
        value = metrics[key]
        criterion = by_metric.get(key)
        if criterion is None:
            lines.append(f"| {key} | {format_value(value)} | — | — |")
            continue
        ev = evaluate_criterion(criterion, metrics)
        lines.append(
            f"| {key} | {format_value(value)} | {criterion['op']} {criterion['value']}"
            f"{provisional_mark(criterion, lang)}{applies_if_text(criterion, lang)} "
            f"| {_status_cell(ev, lang)} |"
        )
    return "\n".join(lines)


def raw_value(value: Any) -> Any:
    return value["value"] if isinstance(value, dict) and "value" in value else value


def check_criterion(value: Any, criterion: dict[str, Any]) -> bool:
    """1 つの合格基準を評価する。"""
    actual = raw_value(value)
    target = criterion["value"]
    op = criterion["op"]
    if actual is None:
        return False
    if op == ">=":
        return bool(actual >= target)
    if op == "<=":
        return bool(actual <= target)
    if op == ">":
        return bool(actual > target)
    if op == "<":
        return bool(actual < target)
    if op == "==":
        return bool(actual == target)
    raise ValueError(f"未知の演算子: {op}")


_NEGATED_OP = {">=": "<", "<=": ">", ">": "<=", "<": ">=", "==": "!="}
APPLIES_IF_KEYS = frozenset({"metric", "op", "value"})
CRITERION_KEYS = frozenset({"metric", "op", "value", "provisional", "applies_if"})


def validate_criterion(criterion: dict[str, Any], where: str = "") -> None:
    """registry の基準 1 つの形を検査する。未知のキーと不正な `applies_if` を黙って無視しない。"""
    unknown = set(criterion) - CRITERION_KEYS
    if unknown:
        raise ValueError(f"{where}基準 {criterion.get('metric')} に未知のキー: {sorted(unknown)}")
    cond = criterion.get("applies_if")
    if cond is None:
        return
    if not isinstance(cond, dict) or set(cond) != APPLIES_IF_KEYS:
        raise ValueError(
            f"{where}基準 {criterion.get('metric')} の applies_if は metric / op / value を持つ辞書"
        )
    if cond["op"] not in (">=", "<=", ">", "<", "=="):
        raise ValueError(
            f"{where}基準 {criterion.get('metric')} の applies_if の演算子: {cond['op']}"
        )


def applies_if_text(criterion: dict[str, Any], lang: str = "ja") -> str:
    """基準の表示に足す適用条件の文字列。条件が無ければ空。"""
    cond = criterion.get("applies_if")
    if not cond:
        return ""
    body = f"{cond['metric']} {cond['op']} {cond['value']}"
    return f" (applies if {body})" if lang == "en" else f"（適用条件: {body}）"


def evaluate_criterion(criterion: dict[str, Any], metrics: dict[str, Any]) -> dict[str, Any]:
    """基準 1 つを結果の指標に照らして評価する（適用条件 `applies_if` を含む。ADR-045）。

    返す辞書の `status`:
    - `pass` / `fail`: 適用され、基準を満たした／満たさない（値が無ければ fail）
    - `na`: 適用条件が偽。合格ではない。判定の AND から外す。`na` に条件の指標・値・否定した演算子を持つ
    - `error`: 適用条件の指標が結果に無い、または来歴ラベルが無い（実装の不備。判定は FAIL）。`error` に理由
    """
    value = metrics.get(criterion["metric"])
    actual = raw_value(value)
    out: dict[str, Any] = {"actual": actual, "value": value, "na": None, "error": ""}
    cond = criterion.get("applies_if")
    if cond:
        cond_value = metrics.get(cond["metric"])
        if cond_value is None or raw_value(cond_value) is None:
            out["status"] = "error"
            out["error"] = f"適用条件の指標 {cond['metric']} が結果に無い"
            return out
        if not (isinstance(cond_value, dict) and cond_value.get("provenance")):
            out["status"] = "error"
            out["error"] = f"適用条件の指標 {cond['metric']} に来歴ラベルが無い"
            return out
        if not check_criterion(cond_value, cond):
            out["status"] = "na"
            out["na"] = {
                "metric": cond["metric"],
                "actual": raw_value(cond_value),
                "op": _NEGATED_OP[cond["op"]],
                "value": cond["value"],
            }
            return out
    out["status"] = "pass" if value is not None and check_criterion(value, criterion) else "fail"
    return out


def na_text(na: dict[str, Any], lang: str = "ja") -> str:
    """N/A の表示（例: `N/A（検出力不足: c13_f_hat = 0.04 < 0.15）`）。"""
    actual = na["actual"]
    shown = f"{actual:.3g}" if isinstance(actual, float) else str(actual)
    cond = f"{na['metric']} = {shown} {na['op']} {na['value']}"
    return f"N/A (insufficient power: {cond})" if lang == "en" else f"N/A（検出力不足: {cond}）"


def _status_cell(ev: dict[str, Any], lang: str = "ja") -> str:
    status = ev["status"]
    if status == "na":
        return na_text(ev["na"], lang)
    if status == "error":
        return f"× ({ev['error']})"
    return "○" if status == "pass" else "×"


def na_criteria(
    criteria: list[dict[str, Any]], metrics: dict[str, Any]
) -> list[tuple[str, dict[str, Any]]]:
    """N/A になった基準の (指標名, `evaluate_criterion` の `na`)。"""
    out: list[tuple[str, dict[str, Any]]] = []
    for c in criteria:
        ev = evaluate_criterion(c, metrics)
        if ev["status"] == "na":
            out.append((c["metric"], ev["na"]))
    return out


def _with_na_note(reason: str, na: list[tuple[str, dict[str, Any]]], lang: str = "ja") -> str:
    """N/A の基準があるときだけ、判定理由の末尾に「N/A は合格ではない」と一覧を足す（ADR-045）。"""
    if not na:
        return reason
    listed = ", ".join(f"{m} = {na_text(n, lang)}" for m, n in na)
    note = (
        f"N/A criteria (excluded from the verdict; N/A is not a pass): {listed}"
        if lang == "en"
        else f"N/A の基準（判定から外した。N/A は合格ではない）: {listed}"
    )
    return f"{reason}\n\n{note}" if reason else note


def render(
    meta: dict[str, Any],
    result: dict[str, Any],
    lang: str = "ja",
    en: dict[str, Any] | None = None,
) -> str:
    """結果ページの markdown を作る。

    `lang="en"` のときは、数値・図・判定はそのままに文章だけを `en` で差し替える。
    `en` に無い項目は日本語のまま残る（未訳が目に見えるようにする）。
    """
    criteria = meta.get("criteria", [])
    source: dict[str, Any] = en or {}
    if lang == "en":
        captions = source.get("figures") or []
        pairs = result.get("figures") or []
        figures = "\n".join(
            f"![{captions[i] if i < len(captions) else name}]({path})"
            for i, (name, path) in enumerate(pairs)
        )
        notes_list = source.get("notes") or result.get("notes") or []
        template = TEMPLATE_EN
    else:
        figures = "\n".join(f"![{name}]({path})" for name, path in (result.get("figures") or []))
        notes_list = result.get("notes") or []
        template = TEMPLATE
    notes = "\n".join(f"- {n}" for n in notes_list)

    def pick(en_key: str, fallback: Any) -> Any:
        return source.get(en_key, fallback) if lang == "en" else fallback

    return template.format(
        id=meta["id"],
        title=pick("title", meta["title"]),
        hypothesis=pick("hypothesis", meta.get("hypothesis", "")),
        planted=pick("planted", meta.get("planted_text", meta.get("planted", ""))),
        control=pick("control", meta.get("control_text", meta.get("control", ""))),
        criteria="、".join(
            f"{c['metric']} {c['op']} {c['value']}{provisional_mark(c)}{applies_if_text(c)}"
            for c in criteria
        )
        if lang != "en"
        else ", ".join(
            f"{c['metric']} {c['op']} {c['value']}{provisional_mark(c, 'en')}"
            f"{applies_if_text(c, 'en')}"
            for c in criteria
        ),
        provenance=meta.get("provenance", ""),
        method=pick("method", result.get("method", "")),
        table=metrics_table(result.get("metrics", {}), criteria, lang),
        figures=figures,
        verdict=result.get("verdict", "PENDING"),
        verdict_reason=_with_na_note(
            pick("verdict_reason", result.get("verdict_reason", "")),
            na_criteria(criteria, result.get("metrics", {})),
            lang,
        ),
        notes=notes,
        script_id=meta["id"].lower().replace("-", "_"),
        ran_at=result.get("ran_at", "-"),
        usd=result.get("usd", 0.0),
    )


def write(
    meta: dict[str, Any], result: dict[str, Any], directory: Path | None = None
) -> list[Path]:
    """結果ページを日本語と英語で書き出す。英訳が無ければ日本語だけ。"""
    base = directory or RESULTS_DIR
    base.mkdir(parents=True, exist_ok=True)
    written = [base / f"{meta['id']}.md"]
    written[0].write_text(render(meta, result), encoding="utf-8")
    en = i18n.load_en().get(meta["id"])
    if en is not None:
        target_en = base / f"{meta['id']}.en.md"
        target_en.write_text(render(meta, result, "en", en), encoding="utf-8")
        written.append(target_en)
    return written
