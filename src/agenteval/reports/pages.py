"""結果ページの生成（`docs/results/EX-Y.md` と `EX-Y.en.md`）。

5 項目はレジストリ（= カタログ）から写す。方法・気づきは実験スクリプトが書いた文章を使う。
数値には必ず来歴ラベルを付ける。

英語版は同じ `result` から描き、文章だけを `experiments/registry.en.yaml` から差し替える
（`reports.i18n`）。数値・図・判定は言語に依存しないので、2 言語で食い違うことがない。
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from agenteval.llm.cost import REPO_ROOT
from agenteval.reports import i18n

RESULTS_DIR = REPO_ROOT / "docs" / "results"

TEMPLATE = """# {id} {title}

## 5項目
- 仮説: {hypothesis}
- 植込み条件: {planted}
- 対照: {control}
- 合格基準: {criteria}
- 来歴: {provenance}

## 方法
{method}

## 結果
{table}
{figures}

## 判定
{verdict}

{verdict_reason}

## 気づき・限界
{notes}

---
生成: `uv run agenteval exp {script_id}` / 実行時刻 {ran_at} / コスト {usd} USD
"""

TEMPLATE_EN = """# {id} {title}

*日本語版: [{id}.md]({id}.md)*

## The five items
- Hypothesis: {hypothesis}
- Planted condition: {planted}
- Control: {control}
- Pass criteria: {criteria}
- Provenance: {provenance}

## Method
{method}

## Results
{table}
{figures}

## Verdict
{verdict}

{verdict_reason}

## Findings and limitations
{notes}

---
Generated by `uv run agenteval exp {script_id}` / run at {ran_at} / cost {usd} USD
"""


def format_value(value: Any) -> str:
    """数値と来歴ラベルを 1 セルにする。"""
    if isinstance(value, dict) and "value" in value:
        raw = value["value"]
        text = (
            f"{raw:.4g}"
            if isinstance(raw, (int, float)) and not isinstance(raw, bool)
            else str(raw)
        )
        return f"{text} [{value.get('provenance', '?')}]"
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def metrics_table(metrics: dict[str, Any], criteria: list[dict[str, Any]], lang: str = "ja") -> str:
    """指標の表。合格基準に対応する行には基準と可否を書く。"""
    by_metric = {c["metric"]: c for c in criteria}
    header = (
        "| Metric | Value (provenance) | Criterion | OK |"
        if lang == "en"
        else "| 指標 | 値（来歴） | 基準 | 判定 |"
    )
    lines = [header, "|---|---|---|---|"]
    for key in sorted(metrics):
        value = metrics[key]
        criterion = by_metric.get(key)
        if criterion is None:
            lines.append(f"| {key} | {format_value(value)} | — | — |")
            continue
        ok = check_criterion(value, criterion)
        lines.append(
            f"| {key} | {format_value(value)} | {criterion['op']} {criterion['value']} | {'○' if ok else '×'} |"
        )
    return "\n".join(lines)


def raw_value(value: Any) -> Any:
    return value["value"] if isinstance(value, dict) and "value" in value else value


def check_criterion(value: Any, criterion: dict[str, Any]) -> bool:
    """1 つの合格基準を評価する。"""
    actual = raw_value(value)
    target = criterion["value"]
    op = criterion["op"]
    if actual is None:
        return False
    if op == ">=":
        return bool(actual >= target)
    if op == "<=":
        return bool(actual <= target)
    if op == ">":
        return bool(actual > target)
    if op == "<":
        return bool(actual < target)
    if op == "==":
        return bool(actual == target)
    raise ValueError(f"未知の演算子: {op}")


def render(
    meta: dict[str, Any],
    result: dict[str, Any],
    lang: str = "ja",
    en: dict[str, Any] | None = None,
) -> str:
    """結果ページの markdown を作る。

    `lang="en"` のときは、数値・図・判定はそのままに文章だけを `en` で差し替える。
    `en` に無い項目は日本語のまま残る（未訳が目に見えるようにする）。
    """
    criteria = meta.get("criteria", [])
    source: dict[str, Any] = en or {}
    if lang == "en":
        captions = source.get("figures") or []
        pairs = result.get("figures") or []
        figures = "\n".join(
            f"![{captions[i] if i < len(captions) else name}]({path})"
            for i, (name, path) in enumerate(pairs)
        )
        notes_list = source.get("notes") or result.get("notes") or []
        template = TEMPLATE_EN
    else:
        figures = "\n".join(f"![{name}]({path})" for name, path in (result.get("figures") or []))
        notes_list = result.get("notes") or []
        template = TEMPLATE
    notes = "\n".join(f"- {n}" for n in notes_list)

    def pick(en_key: str, fallback: Any) -> Any:
        return source.get(en_key, fallback) if lang == "en" else fallback

    return template.format(
        id=meta["id"],
        title=pick("title", meta["title"]),
        hypothesis=pick("hypothesis", meta.get("hypothesis", "")),
        planted=pick("planted", meta.get("planted_text", meta.get("planted", ""))),
        control=pick("control", meta.get("control_text", meta.get("control", ""))),
        criteria="、".join(f"{c['metric']} {c['op']} {c['value']}" for c in criteria)
        if lang != "en"
        else ", ".join(f"{c['metric']} {c['op']} {c['value']}" for c in criteria),
        provenance=meta.get("provenance", ""),
        method=pick("method", result.get("method", "")),
        table=metrics_table(result.get("metrics", {}), criteria, lang),
        figures=figures,
        verdict=result.get("verdict", "PENDING"),
        verdict_reason=pick("verdict_reason", result.get("verdict_reason", "")),
        notes=notes,
        script_id=meta["id"].lower().replace("-", "_"),
        ran_at=result.get("ran_at", "-"),
        usd=result.get("usd", 0.0),
    )


def write(
    meta: dict[str, Any], result: dict[str, Any], directory: Path | None = None
) -> list[Path]:
    """結果ページを日本語と英語で書き出す。英訳が無ければ日本語だけ。"""
    base = directory or RESULTS_DIR
    base.mkdir(parents=True, exist_ok=True)
    written = [base / f"{meta['id']}.md"]
    written[0].write_text(render(meta, result), encoding="utf-8")
    en = i18n.load_en().get(meta["id"])
    if en is not None:
        target_en = base / f"{meta['id']}.en.md"
        target_en.write_text(render(meta, result, "en", en), encoding="utf-8")
        written.append(target_en)
    return written
